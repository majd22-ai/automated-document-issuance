<?php

// Offline encoding only. Originals are never overwritten. No runtime encoding.
$root = dirname(__DIR__);
$sources = [
    'assets/images/banner/header-left.webp' => ['banner/header-left.png', [320, 640, 1024], true],
    'assets/images/banner/header-right.webp' => ['banner/header-right.png', [320, 640, 1024], true],
    'assets/images/banner/yemen-eagle.webp' => ['banner/yemen-eagle.png', [96, 192, 384, 640], false],
    'assets/images/banner/moi-logo.webp' => ['banner/moi-logo.png', [96, 192, 384, 475], false],
    'assets/images/logos/unified-issuance-logo.webp' => ['logos/unified-issuance-logo.png', [128, 256, 512, 640], false],
    'assets/images/banner/civil-registry-logo.webp' => ['banner/cra-logo.png', [96, 192, 384, 640], false],
    'assets/images/services/passports-logo.webp' => ['services/passports-logo.png', [96, 192, 384, 480], false],
    'assets/images/services/traffic-logo.webp' => ['services/traffic-logo.png', [96, 192, 384, 423], false],
    'assets/images/services/identity-document.webp' => ['services/identity-document.jpg', [400, 800, 1000], true],
    'assets/images/services/yemeni-passport.webp' => ['services/yemeni-passport.jpg', [400, 800, 1000], true],
    'assets/images/services/driving-license.webp' => ['services/driving-license.jpg', [400, 800, 1000], true],
    'assets/images/banner/platform-interior.webp' => ['banner/الاصدار الالي من الداخل 2.jfif', [400, 800, 1024], true],
    'assets/images/banner/unified-issuance-building.webp' => ['banner/مجمع الاصدار الالي الموحد.jpg', [480, 960, 1600], true],
];
$directory = $root.'/public/assets/images/responsive';
if (! is_dir($directory)) {
    mkdir($directory, 0755, true);
}
$manifest = [];
foreach ($sources as $fallback => [$source, $widths, $photo]) {
    $path = $root.'/public/assets/images/'.$source;
    $image = imagecreatefromstring(file_get_contents($path));
    if (! $image) {
        throw new RuntimeException('Cannot decode '.$source);
    }
    $slug = pathinfo($fallback, PATHINFO_FILENAME);
    $version = substr(hash('sha256', hash_file('sha256', $path).'responsive-v1-q84-92-avif65'), 0, 10);
    $entry = ['width' => imagesx($image), 'height' => imagesy($image), 'webp' => [], 'avif' => []];
    foreach ($widths as $width) {
        if ($width > imagesx($image)) {
            continue;
        }
        $scaled = imagecreatetruecolor($width, (int) round(imagesy($image) * $width / imagesx($image)));
        imagealphablending($scaled, false);
        imagesavealpha($scaled, true);
        imagefill($scaled, 0, 0, imagecolorallocatealpha($scaled, 0, 0, 0, 127));
        imagecopyresampled($scaled, $image, 0, 0, 0, 0, imagesx($scaled), imagesy($scaled), imagesx($image), imagesy($image));
        $base = 'assets/images/responsive/'.$slug.'-'.$version.'-'.$width;
        if (! imagewebp($scaled, $root.'/public/'.$base.'.webp', $photo ? 84 : 92)) {
            throw new RuntimeException('WebP encoder failed');
        }
        $entry['webp'][$width] = $base.'.webp';
        if ($photo && function_exists('imageavif')) {
            if (! imageavif($scaled, $root.'/public/'.$base.'.avif', 65, 6)) {
                throw new RuntimeException('AVIF encoder failed');
            }
            // Use AVIF only if every selected variant is measurably smaller.
            if (filesize($root.'/public/'.$base.'.avif') < filesize($root.'/public/'.$base.'.webp') * .95) {
                $entry['avif'][$width] = $base.'.avif';
            }
        }
        imagedestroy($scaled);
    }
    if (count($entry['avif']) !== count($entry['webp'])) {
        $entry['avif'] = [];
    }
    $manifest[$fallback] = $entry;
    imagedestroy($image);
    echo $slug.': '.count($entry['webp']).' WebP, '.count($entry['avif']).' AVIF'.PHP_EOL;
}
file_put_contents($root.'/config/responsive_images.php', "<?php\n\n// Generated by scripts/build-responsive-images.php; original public paths are fallbacks.\nreturn ".var_export($manifest, true).";\n");
