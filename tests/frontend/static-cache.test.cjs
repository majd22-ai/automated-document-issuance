const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.BANDWIDTH_TEST_URL;
test('live static cache headers, validators, invalidation and private page isolation', { skip: !base }, async () => {
  const get = (path, headers = {}, method = 'GET') => fetch(base + path, { headers, method });
  const manifest = JSON.parse(fs.readFileSync('public/build/manifest.json'));
  const built = await get('/build/' + manifest['resources/js/app.js'].file);
  assert.match(built.headers.get('cache-control'), /31536000, immutable/);
  const image = await get('/assets/images/banner/header-left.webp');
  assert.equal(image.status, 200); assert.equal((await image.arrayBuffer()).byteLength, fs.statSync('public/assets/images/banner/header-left.webp').size);
  assert.equal(image.headers.get('cache-control'), 'public, max-age=86400');
  const etag = image.headers.get('etag'), modified = image.headers.get('last-modified');
  assert.ok(etag); assert.ok(modified);
  const validated = await get('/assets/images/banner/header-left.webp', { 'If-None-Match': etag });
  assert.equal(validated.status, 304); assert.equal((await validated.arrayBuffer()).byteLength, 0);
  assert.equal((await get('/assets/images/banner/header-left.webp', { 'If-Modified-Since': modified })).status, 304);
  assert.equal((await get('/assets/images/banner/header-left.webp', { 'If-None-Match': '"outdated"', 'If-Modified-Since': modified })).status, 200);
  const responsive = fs.readdirSync('public/assets/images/responsive').find(name => name.endsWith('.avif'));
  const avif = await get('/assets/images/responsive/' + responsive);
  assert.equal(avif.status, 200);
  assert.equal(avif.headers.get('content-type'), 'image/avif');
  assert.equal(avif.headers.get('cache-control'), 'public, max-age=86400');
  assert.equal((await avif.arrayBuffer()).byteLength, fs.statSync('public/assets/images/responsive/' + responsive).size);
  const avifValidated = await get('/assets/images/responsive/' + responsive, { 'If-None-Match': avif.headers.get('etag') });
  assert.equal(avifValidated.status, 304);
  assert.equal((await avifValidated.arrayBuffer()).byteLength, 0);
  const version = Math.floor(fs.statSync('public/js/location-map.js').mtimeMs / 1000);
  assert.equal((await get('/js/location-map.js?v=' + version)).headers.get('cache-control'), 'public, max-age=86400');
  assert.equal((await get('/js/location-map.js?v=1')).headers.get('cache-control'), 'public, max-age=0, must-revalidate');
  assert.equal((await get('/css/icons.css', {}, 'HEAD')).status, 200);
  const login = await get('/login');
  assert.match(login.headers.get('cache-control'), /no-store/); assert.doesNotMatch(login.headers.get('cache-control'), /public/);
  const missing = await get('/assets/not-found.webp');
  assert.equal(missing.status, 404); assert.doesNotMatch(missing.headers.get('cache-control') || '', /public/);
});
